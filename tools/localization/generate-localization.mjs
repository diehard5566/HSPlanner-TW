import { createHash } from 'node:crypto'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseTranslations } from './parse-translations.mjs'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const sourceDir = resolve(root, 'language')
const outputFile = resolve(root, 'frontend/localization/gameTranslations.generated.ts')

const sources = {
  item: 'translationsItem.csv',
  attribute: 'translationsAttributes.csv',
  talent: 'translationsTalent.csv',
  subTalent: 'translationsSubTalent.csv',
  ether: 'translationsEther.csv',
  main: 'translationsMain.csv',
  relic: 'translationsRelic.csv',
  enemy: 'translationsEnemy.csv',
  zone: 'translationsZone.csv',
}

function normalizedEnglish(value) {
  return value.normalize('NFKC').trim().replace(/\s+/g, ' ').toLocaleLowerCase('en-US')
}

const generated = {}
const digest = createHash('sha256')
for (const [namespace, filename] of Object.entries(sources)) {
  const source = await readFile(resolve(sourceDir, filename), 'utf8')
  digest.update(filename).update('\0').update(source)
  const { entries, warnings } = parseTranslations(source, filename)
  for (const warning of warnings) console.warn(warning)

  const byKey = {}
  const byEnglish = {}
  for (const entry of entries) {
    byKey[entry.key] = [entry.en ?? '', entry.zhTW ?? '']
    if (entry.en && entry.zhTW) {
      const normalized = normalizedEnglish(entry.en)
      if (!(normalized in byEnglish)) byEnglish[normalized] = entry.zhTW
    }
  }
  generated[namespace] = { byKey, byEnglish }
}

const namespaceType = Object.keys(sources).map((key) => JSON.stringify(key)).join(' | ')
const body = `// Generated by npm run generate:i18n. DO NOT EDIT MANUALLY.\n` +
  `// Source SHA-256: ${digest.digest('hex')}\n` +
  `export type GameTranslationNamespace = ${namespaceType}\n` +
  `type GeneratedNamespace = { byKey: Record<string, readonly [string, string]>; byEnglish: Record<string, string> }\n` +
  `export const GAME_TRANSLATIONS: Record<GameTranslationNamespace, GeneratedNamespace> = ${JSON.stringify(generated)}\n`

await mkdir(dirname(outputFile), { recursive: true })
await writeFile(outputFile, body, 'utf8')
console.log(`Generated ${outputFile.replace(`${root}/`, '')}`)
