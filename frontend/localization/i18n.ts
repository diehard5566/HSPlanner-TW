const DICTIONARIES: Record<Locale, Record<UiKey, string>> = { en: EN, 'zh-TW': ZH_TW }

export function translateUi(locale: Locale, key: UiKey, values: Record<string, string | number> = {}): string {
  const template = DICTIONARIES[locale][key] ?? EN[key] ?? key
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`))
}

export function useI18n() {
  const locale = useSettings((state) => state.locale)
  const setLocale = useSettings((state) => state.setLocale)
  return { locale, setLocale, t: (key: UiKey, values?: Record<string, string | number>) => translateUi(locale, key, values) }
}
